export function curatedImageUrl(category: string, rank: number): string | null {
  const ids = CURATED_IMAGE_IDS[category];
  if (!ids?.length || rank < 0) return null;
  if (category === "business" && rank % 100 >= ids.length) {
    return `/fallback-images/business-fallback-${rank % 100 - ids.length + 1}.${rank % 100 === 99 ? "svg" : "png"}`;
  }
  return `https://drive.google.com/thumbnail?id=${encodeURIComponent(ids[rank % (category === "business" ? 100 : ids.length)])}&sz=w1600`;
}
